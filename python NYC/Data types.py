                                                                 #Data types in Python

                                        #----->#To check the data type of a variable, we can use the type() function

#1.integer--- 0 to infinity and -1 to -infinity
my_integer = 5
print(my_integer)
print(type(my_integer))


#2.float--- Decimal numbers and Fractions
my_float = 10.5
my_float2 = 22/7
print(my_float)
print(my_float2)
print(type(my_float))
print(type(my_float2))


#3.string
my_string = "Hello, World!"
my_string2 = 'you can store any thing in a string like numbers, letters, and special characters'
my_string3 = "i can use single quote and double quotes in a string"
my_string4 = 'i can use double quotes in single quotes like this "Hello, World!"'
print(my_string)
print(my_string2)
print(my_string3)
print(my_string4)
print(type(my_string))
print(type(my_string2))
print(type(my_string3))
print(type(my_string4))

#4.boolean
my_boolean = True
my_boolean2 = False    #---->Always use capital T and F for True and False

print(my_boolean)
print(my_boolean2)
print(type(my_boolean))
print(type(my_boolean2))

#5.complex numbers
my_complex = 2 + 3j
print(my_complex)
print(type(my_complex))


#6.none
my_none = None
print(my_none)
print(type(my_none))    








